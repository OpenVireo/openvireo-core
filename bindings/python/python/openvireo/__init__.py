"""OpenVireo for Python: the openvireo-core library (accounts, vaults, sync, share links, KDBX).

Everything the core exports is here: ``OvClient``, ``Account``, ``Vault``, ``ServiceAccount``,
``SelfHosted``, ``EventStream``, the records (``ClientConfig``, ``EntryInput`` …), the Host
interfaces (``HttpTransport``, ``SecureStore``, ``BlobCache``, ``Clock``, ``LogSink``), the crypto
helpers and ``OvError``. :mod:`openvireo.hosts` has ready-made Host parts.

Every network or storage call is a coroutine; run it on an asyncio loop. Each takes an optional
``cancel=CancelToken()`` as its last argument; leave it out unless you want to cancel the call from
elsewhere (``token.cancel()`` ends it with ``OvErrorCode.ABORTED``). Cancelling the asyncio task
drops the call too.

Errors are ``OvError`` (the single variant ``OvError.Failure``) with ``code`` (an ``OvErrorCode``),
``wire_code``, ``message``, ``status``, ``retry_after``, ``details`` and ``server_code``::

    try:
        await account.login(openvireo.LoginInput(...))
    except openvireo.OvError as e:
        if e.code == openvireo.OvErrorCode.UNAUTHORIZED:
            ...

The module itself is generated by UniFFI from ``bindings/ov-ffi`` (``openvireo._core``).
"""

