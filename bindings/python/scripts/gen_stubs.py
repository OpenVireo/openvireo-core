#!/usr/bin/env python3
"""Writes the type stubs of the ``openvireo`` package from the module UniFFI generated.

``openvireo._core.ov_ffi`` (UniFFI's output, inside the wheel) annotates every async call with a
required ``CancelToken``; ``openvireo/_compat.py`` makes it ``cancel: CancelToken | None = None`` at
import time. Type checkers read the source, not the runtime, so the package ships stubs:

- ``python/openvireo/_core/ov_ffi.pyi``: every public class, function, record, enum, error and Host
  interface of the generated module, with the signatures as they are *after* ``_compat`` (the
  stub is made by importing ``openvireo`` and inspecting the wrapped callables, so stub and runtime
  agree by construction);
- ``python/openvireo/__init__.pyi``: the package's re-exports.

Both are committed (the sdist and every release wheel carry them; maturin packs files of
``python-source`` and the generated module lands next to the stub). ``cargo xtask python`` runs this
script with ``--check`` after ``maturin develop``, so a core change that alters the surface fails
until the stubs are regenerated with ``cargo xtask python --stubs`` (or
``.venv/bin/python scripts/gen_stubs.py``).

Built with the ``test-server`` feature (``cargo xtask python --smoke``), the module also has the
``opaque_server_*`` test steps; they're left out, so the stub is always the release surface.

Usage: ``python scripts/gen_stubs.py [--check]`` with the package installed (``maturin develop``).
"""

from __future__ import annotations

import argparse
import difflib
import enum
import inspect
import re
import sys
import types
import typing
from collections.abc import Callable, Iterable
from pathlib import Path
from typing import Any

import openvireo
from openvireo._core import ov_ffi

PACKAGE = Path(__file__).resolve().parent.parent / "python" / "openvireo"
CORE_STUB = PACKAGE / "_core" / "ov_ffi.pyi"
INIT_STUB = PACKAGE / "__init__.pyi"

HEADER = (
    "# Generated by bindings/python/scripts/gen_stubs.py from the UniFFI module; don't edit.\n"
    "# Regenerate with `cargo xtask python --stubs`.\n"
)

#: Exports only a ``test-server`` build has (``bindings/ov-ffi/src/opaque.rs``).
TEST_SERVER_ONLY = re.compile(r"^(opaque_server_\w+|OpaqueServer\w+)$")

#: Names ``openvireo/__init__.py`` exports besides the generated module's ``__all__``.
INIT_EXTRAS = ["hosts", "uniffi_set_event_loop", "__version__"]

#: Signatures of the generated dunders that carry no annotations.
DUNDERS = {
    "__eq__": "(self, other: object) -> bool",
    "__ne__": "(self, other: object) -> bool",
    "__str__": "(self) -> str",
    "__repr__": "(self) -> str",
}

Fn = Callable[..., Any]


def release_names(module: types.ModuleType) -> list[str]:
    """``module.__all__`` without the test-server-only exports."""
    names: list[str] = list(module.__all__)
    return [n for n in names if not TEST_SERVER_ONLY.match(n)]


def is_protocol(cls: type) -> bool:
    return bool(cls.__dict__.get("_is_protocol", False))


def variants(cls: type) -> list[tuple[str, type]]:
    """The nested variant classes of a UniFFI enum with data or of an error (subclasses of ``cls``)."""
    return [
        (name, v)
        for name, v in vars(cls).items()
        if inspect.isclass(v) and v is not cls and issubclass(v, cls) and not name.startswith("_")
    ]


class Writer:
    def __init__(self, module: types.ModuleType) -> None:
        self.m = module
        self.ns = vars(module)
        self.imports: set[str] = set()
        self.lines: list[str] = []

    # ------------------------------------------------------------------ types

    def ann(self, a: Any, where: str) -> str:
        """An annotation (a string, as the generated module uses ``from __future__ import
        annotations``, or an object) in stub syntax."""
        if a is inspect.Parameter.empty:
            raise SystemExit(f"gen_stubs: {where} has no annotation")
        if isinstance(a, str):
            try:
                a = eval(a, dict(self.ns))
            except Exception as e:
                raise SystemExit(f"gen_stubs: {where}: can't resolve annotation {a!r}: {e}") from e
        return self.fmt(a, where)

    def fmt(self, t: Any, where: str) -> str:
        if t is None or t is type(None):
            return "None"
        if t is typing.Any:
            self.imports.add("typing")
            return "typing.Any"
        origin = typing.get_origin(t)
        args = typing.get_args(t)
        if origin is typing.Union or origin is types.UnionType:
            parts: list[str] = []
            for a in args:
                s = self.fmt(a, where)
                if s not in parts:
                    parts.append(s)
            if "None" in parts:  # `X | None`, as written by hand
                parts.remove("None")
                parts.append("None")
            return " | ".join(parts)
        if origin in (list, dict, tuple, set, frozenset):
            return f"{origin.__name__}[{', '.join(self.fmt(a, where) for a in args)}]"
        if isinstance(t, type):
            if t.__module__ == "builtins":
                return t.__qualname__
            if t.__module__ == self.m.__name__:
                return t.__qualname__
            self.imports.add(t.__module__)
            return f"{t.__module__}.{t.__qualname__}"
        raise SystemExit(f"gen_stubs: {where}: unsupported annotation {t!r}")

    def converter_type(self, name: str, where: str) -> str:
        """The Python type of a UniFFI converter (``_UniffiFfiConverter<name>``), for the fields the
        generated code leaves unannotated (error variants, tuple variants)."""
        prims = {
            "Boolean": "bool",
            "String": "str",
            "Bytes": "bytes",
            "ByRefBytes": "bytes",
            "Float32": "float",
            "Float64": "float",
        }
        if name in prims:
            return prims[name]
        if re.fullmatch(r"U?Int(8|16|32|64)", name):
            return "int"
        if name == "Timestamp":
            self.imports.add("datetime")
            return "datetime.datetime"
        if name == "Duration":
            self.imports.add("datetime")
            return "datetime.timedelta"
        if name.startswith("Optional"):
            inner = self.converter_type(name[len("Optional") :], where)
            return inner if inner.endswith("| None") else f"{inner} | None"
        if name.startswith("Sequence"):
            return f"list[{self.converter_type(name[len('Sequence') :], where)}]"
        if name.startswith("Type") and inspect.isclass(self.ns.get(name[4:])):
            return name[4:]
        raise SystemExit(f"gen_stubs: {where}: unknown converter {name!r}")

    def variant_field_types(self, enum_name: str) -> dict[str, list[str]]:
        """Variant name → its field types in order, read from the enum's converter ``read``."""
        conv = self.ns[f"_UniffiFfiConverterType{enum_name}"]
        src = inspect.getsource(conv.read)
        out: dict[str, list[str]] = {}
        for block in re.split(r"\n\s*if variant == \d+:", src)[1:]:
            head = re.search(rf"return {re.escape(enum_name)}\.(\w+)\(", block)
            if not head:
                raise SystemExit(f"gen_stubs: can't read the variants of {enum_name}")
            convs = re.findall(r"_UniffiFfiConverter(\w+)\.read\(buf\)", block[head.end() :])
            out[head.group(1)] = [self.converter_type(c, f"{enum_name}.{head.group(1)}") for c in convs]
        return out

    # ------------------------------------------------------------------ output

    def emit(self, indent: int, text: str = "") -> None:
        self.lines.append(("    " * indent + text) if text else "")

    def signature(self, fn: Fn, where: str, drop_first: bool) -> str:
        """``(params) -> ret`` of ``fn`` as it's called now (the ``_compat`` wrapper's
        ``__signature__``)."""
        sig = inspect.signature(fn)
        params = list(sig.parameters.values())
        parts: list[str] = []
        star_done = False
        pos_only = False
        for i, p in enumerate(params):
            if i == 0 and drop_first:
                parts.append(p.name)
                continue
            if p.kind is p.POSITIONAL_ONLY:
                pos_only = True
            elif pos_only:
                parts.append("/")
                pos_only = False
            if p.kind is p.VAR_POSITIONAL:
                ann = "typing.Any" if p.annotation is p.empty else self.ann(p.annotation, f"{where}(*{p.name})")
                self.imports.add("typing")
                parts.append(f"*{p.name}: {ann}")
                star_done = True
                continue
            if p.kind is p.VAR_KEYWORD:
                ann = "typing.Any" if p.annotation is p.empty else self.ann(p.annotation, f"{where}(**{p.name})")
                self.imports.add("typing")
                parts.append(f"**{p.name}: {ann}")
                continue
            if p.kind is p.KEYWORD_ONLY and not star_done:
                parts.append("*")
                star_done = True
            text = f"{p.name}: {self.ann(p.annotation, f'{where}({p.name})')}"
            if p.default is not p.empty:
                text += " = None" if p.default is None else " = ..."
            parts.append(text)
        if pos_only:
            parts.append("/")
        if sig.return_annotation is sig.empty:
            if fn.__name__ not in ("__init__", "uniffi_set_event_loop"):  # both return nothing
                raise SystemExit(f"gen_stubs: {where} has no return annotation")
            ret = "None"
        else:
            ret = self.ann(sig.return_annotation, f"{where} -> ")
        return f"({', '.join(parts)}) -> {ret}"

    def function(self, indent: int, name: str, fn: Fn, where: str, kind: str = "") -> None:
        if kind:
            self.emit(indent, f"@{kind}")
        prefix = "async def" if inspect.iscoroutinefunction(fn) else "def"
        if name in DUNDERS and not any(p.annotation is not p.empty for p in inspect.signature(fn).parameters.values()):
            self.emit(indent, f"{prefix} {name}{DUNDERS[name]}: ...")
            return
        self.emit(
            indent, f"{prefix} {name}{self.signature(fn, where, drop_first=kind != 'staticmethod' and indent > 0)}: ..."
        )

    def members(self, indent: int, cls: type, owner: str) -> int:
        """The public methods of ``cls`` (and ``__init__`` and the dunders above); returns how many."""
        n = 0
        for attr, raw in vars(cls).items():
            if attr.startswith("_") and attr != "__init__" and attr not in DUNDERS:
                continue
            kind = ""
            fn = raw
            if isinstance(raw, (classmethod, staticmethod)):
                kind = type(raw).__name__
                fn = raw.__func__
            # (typing.Protocol puts its own __init__ in the class)
            if not inspect.isfunction(fn) or fn.__module__ != self.m.__name__:
                continue
            self.function(indent, attr, fn, f"{owner}.{attr}", kind)
            n += 1
        return n

    def init_fields(self, indent: int, cls: type, where: str) -> None:
        """Typed attributes for a record (from its annotated ``__init__``)."""
        init = cls.__dict__.get("__init__")
        if not inspect.isfunction(init):
            return
        for p in list(inspect.signature(init).parameters.values())[1:]:
            if p.kind in (p.VAR_POSITIONAL, p.VAR_KEYWORD):
                continue
            self.emit(indent, f"{p.name}: {self.ann(p.annotation, f'{where}.{p.name}')}")

    def bases(self, cls: type) -> str:
        names = [b.__qualname__ for b in cls.__bases__ if b.__module__ == self.m.__name__]
        if is_protocol(cls):
            self.imports.add("typing")
            names.append("typing.Protocol")
        return f"({', '.join(names)})" if names else ""

    def plain_class(self, name: str, cls: type) -> None:
        """An object, a record, a Host interface or a protocol."""
        self.emit(0, f"class {name}{self.bases(cls)}:")
        start = len(self.lines)
        is_object = "_handle" in inspect.get_annotations(cls)
        if not is_object and not is_protocol(cls):
            self.init_fields(1, cls, name)
        self.members(1, cls, name)
        if len(self.lines) == start:
            self.lines[-1] += " ..."

    def enum_class(self, name: str, cls: type[enum.Enum]) -> None:
        self.imports.add("enum")
        self.emit(0, f"class {name}(enum.Enum):")
        for member in cls:
            self.emit(1, f"{member.name} = {member.value!r}")
        self.members(1, cls, name)

    def data_enum(self, name: str, cls: type) -> None:
        """A UniFFI enum with data: the variants are nested subclasses."""
        types_ = self.variant_field_types(name)
        self.emit(0, f"class {name}:")
        init = cls.__dict__.get("__init__")
        if inspect.isfunction(init):
            self.function(1, "__init__", init, f"{name}.__init__")
        for vname, v in variants(cls):
            self.variant(1, name, vname, v, types_.get(vname, []))
        for attr, raw in vars(cls).items():
            if inspect.isfunction(raw) and not attr.startswith("_"):
                self.function(1, attr, raw, f"{name}.{attr}")

    def variant(self, indent: int, owner: str, vname: str, v: type, fields: list[str]) -> None:
        self.emit(indent, f"class {vname}({owner}):")
        params = self.variant_init(v)
        if params and params[0].kind is params[0].VAR_POSITIONAL:  # a tuple variant
            args = ", ".join(f"v{i}: {t}" for i, t in enumerate(fields))
            self.emit(
                indent + 1,
                f"def __init__(self, {args}, /) -> None: ..." if fields else "def __init__(self) -> None: ...",
            )
            if len(set(fields)) == 1:
                self.emit(indent + 1, f"def __getitem__(self, index: int) -> {fields[0]}: ...")
            elif fields:
                self.imports.add("typing")
                for i, t in enumerate(fields):
                    self.emit(indent + 1, "@typing.overload")
                    self.emit(indent + 1, f"def __getitem__(self, index: typing.Literal[{i}]) -> {t}: ...")
        else:
            named = self.variant_fields(owner, vname, v, fields)
            for n, t in named:
                self.emit(indent + 1, f"{n}: {t}")
            args = "".join(f", {n}: {t}" for n, t in named)
            self.emit(indent + 1, f"def __init__(self{args}) -> None: ...")

    @staticmethod
    def variant_init(v: type) -> list[inspect.Parameter]:
        """The ``__init__`` parameters (without ``self``) of a variant class. A data enum's variant
        is ``type(name, (Variant, Owner), {})`` at runtime; its body is the first base."""
        body = v.__mro__[1] if "__init__" not in v.__dict__ and len(v.__mro__) > 1 else v
        init = body.__dict__.get("__init__")
        return list(inspect.signature(init).parameters.values())[1:] if inspect.isfunction(init) else []

    def variant_fields(self, owner: str, vname: str, v: type, fields: list[str]) -> list[tuple[str, str]]:
        """(name, type) of a variant with named fields; the types come from the annotations, or from
        the converter when the generated ``__init__`` has none (error variants)."""
        where = f"{owner}.{vname}"
        params = self.variant_init(v)
        if params and params[0].kind is params[0].VAR_POSITIONAL:
            return []
        names = [p.name for p in params]
        annotated = all(p.annotation is not p.empty for p in params)
        types_ = [self.ann(p.annotation, f"{where}.{p.name}") for p in params] if annotated else fields
        if len(types_) != len(names):
            raise SystemExit(f"gen_stubs: {where}: {len(names)} fields but {len(types_)} types")
        return list(zip(names, types_, strict=True))

    def error_class(self, name: str, cls: type) -> None:
        vs = variants(cls)
        bases = ", ".join(b.__qualname__ for b in cls.__bases__)
        if not vs:
            self.emit(0, f"class {name}({bases}): ...")
            return
        types_ = self.variant_field_types(name)
        self.emit(0, f"class {name}({bases}):")
        # The fields every variant has (all of them for OvError, whose one variant is Failure), so
        # `except OvError as e: e.code` type-checks as it runs.
        fields = [self.variant_fields(name, vname, v, types_.get(vname, [])) for vname, v in vs]
        for n, t in fields[0]:
            if all((n, t) in f for f in fields[1:]):
                self.emit(1, f"{n}: {t}")
        for vname, v in vs:
            self.variant(1, name, vname, v, types_.get(vname, []))

    # ------------------------------------------------------------------ module

    def core(self) -> str:
        names = release_names(self.m)
        body_start = len(self.lines)
        for name in names:
            obj = getattr(self.m, name)
            self.emit(0)
            if inspect.isclass(obj):
                if issubclass(obj, enum.Enum):
                    self.enum_class(name, obj)
                elif issubclass(obj, BaseException):
                    self.error_class(name, obj)
                elif variants(obj):
                    self.data_enum(name, obj)
                else:
                    self.plain_class(name, obj)
            elif inspect.isfunction(obj):
                self.function(0, name, obj, name)
            else:
                raise SystemExit(f"gen_stubs: don't know how to stub {name} ({type(obj).__name__})")
        # Exported by openvireo/__init__.py, not in the generated __all__.
        self.emit(0)
        self.function(0, "uniffi_set_event_loop", self.m.uniffi_set_event_loop, "uniffi_set_event_loop")
        body = self.lines[body_start:]
        head = [HEADER.rstrip("\n"), "", *(f"import {i}" for i in sorted(self.imports)), ""]
        head.append("__all__ = [")
        head += [f'    "{n}",' for n in names]
        head.append("]")
        return "\n".join(head + body) + "\n"


def init_stub(names: Iterable[str]) -> str:
    exported = [*names, *INIT_EXTRAS]
    lines = [
        HEADER.rstrip("\n"),
        "",
        "from . import hosts as hosts",
        "from ._core.ov_ffi import *",
        "from ._core.ov_ffi import uniffi_set_event_loop as uniffi_set_event_loop",
        "",
        "__version__: str",
        "_CANCEL_OPTIONAL: list[str]",
        "",
        "__all__ = [",
        *(f'    "{n}",' for n in exported),
        "]",
    ]
    return "\n".join(lines) + "\n"


def generate() -> dict[Path, str]:
    """The stubs, by path."""
    assert openvireo._CANCEL_OPTIONAL, "openvireo._compat didn't run"
    return {CORE_STUB: Writer(ov_ffi).core(), INIT_STUB: init_stub(release_names(ov_ffi))}


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="fail if the committed stubs are out of date")
    args = parser.parse_args(argv)
    stale = []
    for path, text in generate().items():
        old = path.read_text() if path.exists() else ""
        if old == text:
            continue
        if args.check:
            stale.append(path)
            diff = difflib.unified_diff(old.splitlines(), text.splitlines(), str(path), "generated", lineterm="", n=1)
            sys.stderr.write("\n".join(list(diff)[:60]) + "\n")
        else:
            path.write_text(text)
            print(f"wrote {path}")
    if stale:
        sys.stderr.write(
            "gen_stubs: the type stubs are out of date with the generated module; run "
            "`cargo xtask python --stubs` and commit them\n"
        )
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
