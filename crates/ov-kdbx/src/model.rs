#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn protected_values_are_redacted_in_debug() {
        let f = StringField::new("Password", "hunter2", true);
        assert!(!format!("{f:?}").contains("hunter2"));
        let f = StringField::new("UserName", "alice", false);
        assert!(format!("{f:?}").contains("alice"));
        let b = Binary { data: Zeroizing::new(b"secret file".to_vec()), protected: true };
        assert!(!format!("{b:?}").contains("secret"));
    }

    #[test]
    fn new_entry_has_standard_fields() {
        let e = Entry::new(Uuid::from_bytes([1; 16]), 1_700_000_000);
        let keys: Vec<&str> = e.strings.iter().map(|f| f.key.as_str()).collect();
        assert_eq!(keys, STANDARD_FIELDS);
        assert!(e.field("Password").unwrap().protected);
        assert_eq!(e.title(), "");
        assert_eq!(e.times.location_changed, 1_700_000_000);
    }
}
