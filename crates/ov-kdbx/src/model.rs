//! The KDBX document as plain Rust values: what the reader produces, the writer consumes and the
//! merge (`ov-merge`) works on.
//!
//! **Frozen contract** (rust-core-tasks.md §2.5, tag `contract-v1`). The model is lossless: every
//! element KeePassXC, KeePass 2.x, kdbxweb, Strongbox and the iOS app write either has a field here
//! or survives in an `unknown` list ([`XmlElement`]) on [`Database`], [`Meta`], [`Group`], [`Entry`]
//! or [`AutoType`], and is written back unchanged.
//!
//! Conventions:
//! - Times are [`Timestamp`]s: `i64` Unix **seconds**, as KDBX 4 stores them (KDBX 3.1's ISO 8601
//!   text is converted on read; sub-second parts are dropped).
//! - Lists keep file order. Entry strings stay in the order they were read, so a save doesn't
//!   reorder custom fields.
//! - Values that are protected in the file ([`StringField::protected`], [`Binary::protected`]) are
//!   held in [`Zeroizing`] buffers and are redacted in `Debug` output. Other strings are plain.
//! - Per-save secrets (master seed, encryption IV, inner stream key, KDF salt or seed regenerated by
//!   the writer) are not part of the model. Values derived on save (the KDBX 3.1 `HeaderHash`, the
//!   KDBX 4 header HMAC) aren't either.
//!
//! Reference: KeePassXC `src/format/KdbxXmlReader.cpp` (every element name it reads has a field
//! here), `src/core/{Entry,Group,Metadata}.h`, and the iOS app's `OpenVireoCore/KDBX/Model.swift`.

use std::fmt;

pub use uuid::Uuid;
use zeroize::Zeroizing;

/// Unix time in whole seconds (KDBX 4's representation).
pub type Timestamp = i64;

/// The five standard entry string keys, in KeePass's order.
pub const STANDARD_FIELDS: [&str; 5] = ["Title", "UserName", "Password", "URL", "Notes"];

/// An element this model has no field for, kept verbatim so it round-trips (rust-core §2.5).
///
/// `text` is the element's text content in clear. If the element carried `Protected="True"`, the
/// attribute stays in `attributes` and the reader has already removed the inner-stream encryption;
/// the writer applies it again in document order.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct XmlElement {
    /// Local element name, e.g. `"BrowserSettings"`.
    pub name: String,
    /// Attributes in file order.
    pub attributes: Vec<(String, String)>,
    /// Text content (empty when none). Mixed content keeps only the concatenated text.
    pub text: String,
    /// Child elements in file order.
    pub children: Vec<XmlElement>,
}

/// A whole KDBX file: outer-header settings, `<Meta>`, the group tree, deleted objects and the
/// attachment pool.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Database {
    /// Outer-header settings the file is saved with.
    pub header: Header,
    /// `<Meta>`.
    pub meta: Meta,
    /// `<Root>`'s single top-level group.
    pub root: Group,
    /// `<Root><DeletedObjects>`: tombstones the merge uses to tell deletions from additions.
    pub deleted_objects: Vec<DeletedObject>,
    /// The attachment pool: KDBX 4 inner-header binaries, or KDBX 3.1 `<Meta><Binaries>` in ID
    /// order. [`BinaryRef::index`] points into it. Identical attachments may share one item.
    pub binaries: Vec<Binary>,
    /// Unknown children of `<KeePassFile>`.
    pub unknown_file: Vec<XmlElement>,
    /// Unknown children of `<Root>`.
    pub unknown_root: Vec<XmlElement>,
}

/// KDBX file version as read (`major.minor`, e.g. 4.0, 4.1, 3.1). Writers emit KDBX 4.x.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub struct KdbxVersion {
    /// Major version (3 or 4).
    pub major: u16,
    /// Minor version.
    pub minor: u16,
}

/// The outer header's settings (not its per-save random values).
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Header {
    /// The version the file was read as.
    pub version: KdbxVersion,
    /// Payload cipher.
    pub cipher: Cipher,
    /// Payload compression.
    pub compression: Compression,
    /// Key derivation for the composite key.
    pub kdf: Kdf,
    /// KDBX 4 `PublicCustomData` (readable without the key), if present.
    pub public_custom_data: Option<VariantDictionary>,
    /// Outer-header fields this model doesn't know, as `(field id, raw value)`, in file order.
    pub unknown_fields: Vec<(u8, Vec<u8>)>,
}

/// Payload cipher (outer header `CipherID`).
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum Cipher {
    /// AES-256-CBC, `31c1f2e6-bf71-4350-be58-05216afc5aff`.
    Aes256Cbc,
    /// ChaCha20, `d6038a2b-8b6f-4cb5-a524-339a31dbb59a` (vault default).
    ChaCha20,
    /// Twofish-CBC, `ad68f29f-576f-4bb9-a36a-d47af965346c` (recognised; may be unsupported).
    Twofish,
    /// Any other cipher UUID.
    Other(Uuid),
}

/// Payload compression.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq, Hash)]
pub enum Compression {
    /// No compression.
    None,
    /// GZip (KeePass default).
    #[default]
    Gzip,
}

/// Argon2 flavour used by a KDBX KDF.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum Argon2Type {
    /// Argon2d, `ef636ddf-8c29-444b-91f7-a9a403e30a0c`.
    D,
    /// Argon2id, `9e298b19-56db-4773-b23d-fc3ec6f0a1e6`.
    Id,
}

/// Key derivation function parameters (KDBX 4 `KdfParameters`; KDBX 3.1's TransformSeed and
/// TransformRounds read as [`Kdf::AesKdf`]).
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum Kdf {
    /// AES-KDF, `c9d9f39a-628a-4460-bf74-0d08c18a4fea` (or `7c02bb82-…` for the KDBX 4 variant).
    AesKdf {
        /// Transform rounds (`R`).
        rounds: u64,
        /// Seed (`S`), 32 bytes.
        seed: Vec<u8>,
    },
    /// Argon2d or Argon2id.
    Argon2 {
        /// Which Argon2.
        kind: Argon2Type,
        /// Salt (`S`).
        salt: Vec<u8>,
        /// Memory in **bytes** (`M`), as KDBX stores it.
        memory: u64,
        /// Iterations (`I`).
        iterations: u64,
        /// Parallelism (`P`).
        parallelism: u32,
        /// Argon2 version (`V`), 0x13 in practice.
        version: u32,
        /// Optional secret key (`K`).
        secret: Option<Vec<u8>>,
        /// Optional associated data (`A`).
        associated_data: Option<Vec<u8>>,
    },
    /// A KDF this model doesn't know: its whole parameter dictionary, including `$UUID`.
    Other(VariantDictionary),
}

/// A KDBX 4 VariantDictionary (`KdfParameters`, `PublicCustomData`), in file order.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct VariantDictionary {
    /// Format version (0x0100).
    pub version: u16,
    /// Items in file order.
    pub items: Vec<(String, Variant)>,
}

/// One VariantDictionary value.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum Variant {
    /// Type 0x04.
    U32(u32),
    /// Type 0x05.
    U64(u64),
    /// Type 0x08.
    Bool(bool),
    /// Type 0x0C.
    I32(i32),
    /// Type 0x0D.
    I64(i64),
    /// Type 0x18 (UTF-8).
    String(String),
    /// Type 0x42.
    Bytes(Vec<u8>),
}

/// `<Meta>`.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Meta {
    /// `Generator`.
    pub generator: String,
    /// `DatabaseName`.
    pub database_name: String,
    /// `DatabaseNameChanged`.
    pub database_name_changed: Option<Timestamp>,
    /// `DatabaseDescription`.
    pub database_description: String,
    /// `DatabaseDescriptionChanged`.
    pub database_description_changed: Option<Timestamp>,
    /// `DefaultUserName`.
    pub default_user_name: String,
    /// `DefaultUserNameChanged`.
    pub default_user_name_changed: Option<Timestamp>,
    /// `MaintenanceHistoryDays`.
    pub maintenance_history_days: u32,
    /// `Color` (e.g. `#FF0000`, or empty).
    pub color: String,
    /// `MasterKeyChanged`.
    pub master_key_changed: Option<Timestamp>,
    /// `MasterKeyChangeRec` (days, -1 = never).
    pub master_key_change_rec: i64,
    /// `MasterKeyChangeForce` (days, -1 = never).
    pub master_key_change_force: i64,
    /// `MemoryProtection`.
    pub memory_protection: MemoryProtection,
    /// `CustomIcons`.
    pub custom_icons: Vec<CustomIcon>,
    /// `RecycleBinEnabled`.
    pub recycle_bin_enabled: bool,
    /// `RecycleBinUUID` (`None` when absent or the all-zero UUID).
    pub recycle_bin_uuid: Option<Uuid>,
    /// `RecycleBinChanged`.
    pub recycle_bin_changed: Option<Timestamp>,
    /// `EntryTemplatesGroup`.
    pub entry_templates_group: Option<Uuid>,
    /// `EntryTemplatesGroupChanged`.
    pub entry_templates_group_changed: Option<Timestamp>,
    /// `HistoryMaxItems` (-1 = unlimited).
    pub history_max_items: i32,
    /// `HistoryMaxSize` in bytes (-1 = unlimited).
    pub history_max_size: i64,
    /// `LastSelectedGroup`.
    pub last_selected_group: Option<Uuid>,
    /// `LastTopVisibleGroup`.
    pub last_top_visible_group: Option<Uuid>,
    /// `CustomData` (OpenVireo keeps `KPXC_SYNC_GENERATION` and remote settings here).
    pub custom_data: Vec<CustomDataItem>,
    /// `SettingsChanged` (KDBX 4.1).
    pub settings_changed: Option<Timestamp>,
    /// Unknown children of `<Meta>`.
    pub unknown: Vec<XmlElement>,
}

