#!/bin/sh
# Builds the legacy OPAQUE WASM module (feature legacy-c-abi, the default) from this workspace and writes it,
# base64-inlined, to OUT_DIR/opaque-wasm.js, plus OUT_DIR/THIRD-PARTY-LICENSES.txt.
#
#   crates/ov-opaque/build.sh [OUT_DIR]      default OUT_DIR: <workspace>/target/opaque-wasm
#   e.g. from openvireo-sdk: ../openvireo-core/crates/ov-opaque/build.sh packages/sdk/vendor/opaque
#
# `cargo rustc --crate-type cdylib` is used because Cargo drops `-C lto` when a package's crate types include
# rlib, and ov-opaque is also an rlib for the rest of the core. Paths are remapped so the output doesn't
# depend on the checkout or the cargo home (reproducible with the root rust-toolchain.toml and Cargo.lock).
set -eu
root=$(cd "$(dirname "$0")/../.." && pwd)
out_dir=${1:-$root/target/opaque-wasm}
mkdir -p "$out_dir"
out_dir=$(cd "$out_dir" && pwd)
CARGO_HOME=${CARGO_HOME:-$HOME/.cargo}
target_dir=$root/target/opaque-wasm-build
cd "$root"
RUSTFLAGS="--remap-path-prefix=$root=/src --remap-path-prefix=$CARGO_HOME=/cargo" \
  cargo rustc --locked --release --target wasm32-unknown-unknown -p ov-opaque --lib --crate-type cdylib \
  --target-dir "$target_dir"
wasm=$target_dir/wasm32-unknown-unknown/release/ov_opaque.wasm
out=$out_dir/opaque-wasm.js
{
  echo "// Generated by openvireo-core crates/ov-opaque/build.sh (opaque-ke 4.0.1, legacy C ABI). Do not edit."
  echo "// SPDX-License-Identifier: MIT OR Apache-2.0"
  printf 'export default "%s";\n' "$(base64 < "$wasm" | tr -d '\n')"
} > "$out"
# Notices for every crates.io crate compiled into the module (MIT text for dual-licensed crates). Workspace
# crates (ov-*) are this repo's own code, MIT OR Apache-2.0.
notices=$out_dir/THIRD-PARTY-LICENSES.txt
{
  echo "Third-party code compiled into opaque-wasm.js (generated by openvireo-core crates/ov-opaque/build.sh)."
  cargo tree --locked -p ov-opaque --target wasm32-unknown-unknown -e normal,no-proc-macro --prefix none -f '{p}|{l}' \
    | grep -v '^ov-' | sed 's/ (\*)$//' | sort -u | while IFS='|' read -r pkg lic; do
      dir=$(ls -d "$CARGO_HOME"/registry/src/*/"$(echo "$pkg" | sed 's/ v/-/')" | head -1)
      file=""
      for f in LICENSE-MIT LICENSE-MIT.md LICENSE LICENSE-BSD LICENSE-APACHE LICENSE-APACHE.md; do [ -f "$dir/$f" ] && { file=$dir/$f; break; }; done
      [ -n "$file" ] || { echo "no licence file for $pkg" >&2; exit 1; }
      printf '\n================================================================================\n%s (%s)\n\n' "$pkg" "$lic"
      tr -d '\r' < "$file"
    done
} > "$notices"
echo "wasm  $(shasum -a 256 "$wasm" | cut -d' ' -f1)  $(wc -c < "$wasm" | tr -d ' ') bytes"
echo "js    $(shasum -a 256 "$out" | cut -d' ' -f1)  $out"
